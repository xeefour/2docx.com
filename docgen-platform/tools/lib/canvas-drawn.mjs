/**
 * เกณฑ์ "canvas วาดเสร็จแล้วจริง" — ใช้ร่วมกันทุกสคริปต์ที่รอ pdf.js
 *
 * ── ทำไมต้องมีตัวกลาง ───────────────────────────────────────────
 * หลายสคริปต์เขียนว่า `c.width > 400 && c.height > 400` มานาน
 * ตอนนี้กระดาษถูกย่อให้**พอดีกล่องพรีวิว** แล้ว (ดู `tools/test-fit-page.mjs`)
 * บนจอเตี้ยหรือตอนเปิดไม้บรรทัด กระดาษกว้างแค่ ~280px
 * → เกณฑ์ 400px ผ่าน**ไม่ได้แม้กระดาษวาดเสร็จแล้ว** แล้วสคริปต์ตกทั้งชุด
 * ทั้งที่พรีวิวไม่ได้พัง (เคยเจอกับ test-ruler-ui · test-download-pages · test-print-preview)
 *
 * ── เกณฑ์ที่ใช้ ──────────────────────────────────────────────────
 * `<canvas>` ที่ยังไม่เคยวาดมีขนาดเริ่มต้น **300×150** (default ของเบราว์เซอร์)
 * กระดาษจริง (A4 แนวตั้งหรือแนวนอน) สูงเสมอ และสูงกว่า 200px แน่นอนเมื่อวาดเสร็จ
 * จึงใช้**ความสูง**เป็นหลัก ไม่ใช้ความกว้าง → ไม่ผูกกับขนาดกล่องพรีวิวอีก
 */

/** selector ของ canvas หน้าหลักในกล่องพรีวิว (เจาะ `.docstage__page` ไม่ให้ไปโดนรูปย่อ) */
export const MAIN_CANVAS_SELECTOR = '.docpage .docstage__page canvas'

/**
 * นิพจน์ JS สำหรับ `waitFor()` — คืน `true` เมื่อ canvas หน้าหลักวาดเสร็จแล้ว
 * @param {string} selector selector ของ canvas (ค่าเริ่มต้นคือหน้าหลักในกล่องพรีวิว)
 */
export function canvasDrawnJs(selector = MAIN_CANVAS_SELECTOR) {
  return `(() => {
    const c = document.querySelector(${JSON.stringify(selector)})
    if (!c) return false
    // 300×150 = ค่าเริ่มต้นที่ยังไม่วาด · กระดาษจริงสูงกว่านี้เสมอ
    return c.height > 200 && c.width > 60
  })()`
}

async function runProve() {
  console.log('\n=== โหมดพิสูจน์: ฉีดบั๊กแล้วตัวตรวจต้องตก ===\n')
  let broken = 0
  const report = (name, caught, detail) => {
    console.log(`${caught ? 'ผ่าน' : 'ตก  '}  ${name}${detail ? ' — ' + detail : ''}`)
    if (!caught) broken++
  }

  // 1. ค่าที่คู่มือระบุว่าต้องได้ แต่ใส่ข้อมูลผิด → ตัวตรวจต้องจับได้
  const t1 = await checkCase({
    name: 'ใส่ข้อมูลผิด',
    template: { blocks: ['ชื่อ: {d.ชื่อ}'] },
    data: { ...DATA, ชื่อ: 'ไม่ใช่สมชาย' },
    expect: ['ชื่อ: สมชาย'],
  })
  report('จับได้เมื่อข้อมูลไม่ตรง', !t1.ok, t1.detail)

  // 2. tag ที่ไม่มีจริง → ต้องตก
  const t2 = await checkCase({
    name: 'ฟิลด์ไม่มีอยู่จริง',
    template: { blocks: ['ชื่อ: {d.ไม่มีฟิลด์นี้}'] },
    data: DATA,
    expect: ['ชื่อ: สมชาย'],
  })
  report('จับได้เมื่อฟิลด์ไม่มีอยู่จริง', !t2.ok, t2.detail)

  // 3. เนื้อหาที่ "ไม่ควรอยู่" ถ้าโผล่ต้องถูกจับ
  //    ต้องออกแบบให้ค่าที่ถูกกับค่าที่ไม่ควรอยู่ อยู่ในเอกสารเดียวกันจริง ๆ
  //    มิฉะนั้น reject จะไม่มีโอกาสทำงาน แล้วผลจะเป็น "ผ่าน" ทั้งที่ตัวตรวจใช้ไม่ได้
  const t3 = await checkCase({
    name: 'เนื้อหาที่ไม่ควรอยู่โผล่ขึ้นมา',
    template: {
      blocks: ['ผ่าน={d.ชื่อ}', "{d.ชื่อ:ifEQ('สมชาย'):show('เนื้อหาที่ไม่ควรอยู่')}"],
    },
    data: DATA,
    expect: ['ผ่าน=สมชาย'],
    reject: ['เนื้อหาที่ไม่ควรอยู่'],
  })
  report('จับได้เมื่อเนื้อหาที่ไม่ควรอยู่โผล่มา', !t3.ok && /เจอสิ่งที่ไม่ควรมี/.test(t3.detail), t3.detail)

  // 4. วงที่ไม่มีตัวปิด → docserver ต้องปฏิเสธ และตัวตรวจต้องตก
  const t4 = await checkCase({
    name: 'วงไม่มีตัวปิด',
    template: {
      blocks: ['ตาราง'],
      tables: [[['รายการ'], ['{d.รายการ[i].ชื่อ}']]],
    },
    data: DATA,
    expect: ['ตาราง', 'รายการ', 'ค่าเช่าค่าต๋าง'],
  })
  report('จับได้เมื่อวงไม่มีตัวปิด', !t4.ok && /no corresponding/.test(t4.detail), t4.detail)

  // 5. ชื่อฟิลด์ที่มีช่องว่างทำให้เนื้อหาหายไปทั้งย่อหน้า
  const t5 = await checkCase({
    name: 'เนื้อหาหายเพราะชื่อฟิลด์มีช่องว่าง',
    template: { blocks: ['ก่อน {d.ชื่อ เต็ม} หลัง'] },
    data: { ...DATA, 'ชื่อ เต็ม': 'สมชาย รักดี' },
    expect: ['ก่อน สมชาย รักดี หลัง'],
  })
  report('จับได้เมื่อชื่อฟิลด์มีช่องว่าง', !t5.ok, t5.detail)

  // 6. ถ้าตัวตรวจใช้ไม่ได้จริง ต้องไม่ผ่านทั้งหมด
  const real = await checkCase({
    name: 'เคสปกติต้องผ่าน',
    template: { blocks: ['ชื่อ: {d.ชื่อ}'] },
    data: DATA,
    expect: ['ชื่อ: สมชาย'],
  })
  report('เคสปกติยังผ่านอยู่ (กันการตรวจที่ตกทุกข้อ)', real.ok, real.detail)

  console.log(`\n${broken === 0 ? 'ผ่านทั้งหมด — ตัวตรวจจับบั๊กได้จริง' : 'ตก ' + broken + ' ข้อ — ตัวตรวจอาจใช้ไม่ได้'}`)
  process.exit(broken === 0 ? 0 : 1)
}

// ─────────────────────────────────────────────────────────────
// ตัวรันหลัก
// ─────────────────────────────────────────────────────────────

async function runVerify() {
  const only = process.argv.find((a) => a.startsWith('--only='))?.slice(7)
  let pass = 0
  let total = 0
  const failed = []

  for (const g of GROUPS) {
    if (only && !g.key.includes(only)) continue
    console.log(`\n=== ${g.key} ===`)
    for (const c of g.cases) {
      total++
      const r = await checkCase({ ...c, data: c.data ?? DATA })
      if (r.ok) {
        pass++
        console.log(`ผ่าน  ${c.name}`)
      } else {
        failed.push(c.name)
        console.log(`ตก    ${c.name}\n        ${r.detail}`)
      }
    }
  }

  if (!only || only === 'ข้อจำกัด') {
    console.log(`\n=== ข้อจำกัดของระบบ (ต้องใช้ไม่ได้จริง) ===`)
    for (const u of UNUSABLE) {
      total++
      let out = ''
      let detail = ''
      let rendered = false
      try {
        const buf = await render(buildDocx({ blocks: [u.tag] }), DATA, 'docx', {})
        out = extractLines(buf, ['word/document.xml']).join('\n')
        rendered = true
      } catch (err) {
        detail = String(err.message)
      }
      // ผ่าน = ล้มเหลวตรงตามที่คู่มืออ้าง ไม่ใช่แค่ล้มเหลวทางอื่น
      const confirmed = u.error ? u.error.test(detail) : rendered && !u.mustNotShow.test(out)
      if (confirmed) {
        pass++
        console.log(`ผ่าน  ${u.name} ใช้ไม่ได้จริง`)
      } else {
        failed.push(u.name)
        const why = u.error
          ? `ไม่ได้ล้มด้วยข้อความที่คาด: ${detail.replace(/\s+/g, ' ').slice(0, 110)}`
          : `ยังทำได้ ได้เป็น ${JSON.stringify(out.slice(0, 70))}`
        console.log(`ตก    ${u.name} — ${why}`)
      }
    }
  }

  console.log(`\n${'='.repeat(56)}`)
  console.log(`${pass}/${total} ผ่าน`)
  if (failed.length) {
    console.log(`ตก: ${failed.join(', ')}`)
    process.exit(1)
  }
}

